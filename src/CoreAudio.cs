    [StructLayout(LayoutKind.Sequential)]
    public struct PropertyKey
    {
        public Guid Fmtid;
        public int Pid;
        public PropertyKey(string g, int pid) { Fmtid = new Guid(g); Pid = pid; }
        public bool Is(PropertyKey o) => Fmtid == o.Fmtid && Pid == o.Pid;
    }

    // PROPVARIANT: vt at 0, value at 8; 16 bytes on x86, 24 on x64
    [StructLayout(LayoutKind.Sequential)]
    public struct PropVariant
    {
        public ushort Vt;
        ushort r1, r2, r3;
        public IntPtr P;
        IntPtr p2;

        public string AsString() => Vt == 31 && P != IntPtr.Zero ? Marshal.PtrToStringUni(P) : null;   // VT_LPWSTR
        public int AsInt() => Vt == 19 || Vt == 3 ? unchecked((int)(uint)(P.ToInt64() & 0xFFFFFFFF)) : -1; // VT_UI4 / VT_I4
    }

